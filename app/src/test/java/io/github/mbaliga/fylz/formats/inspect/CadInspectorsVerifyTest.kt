    private class CountingSource(val inner: ByteSource) : ByteSource {
        var bytes = 0L
        var calls = 0
        override val size: Long get() = inner.size
        override fun read(offset: Long, length: Int): ByteArray {
            calls++
            if (offset >= 0 && length > 0) bytes += maxOf(0L, minOf(length.toLong(), inner.size - offset))
            return inner.read(offset, length)
        }
    }

    private class VirtualSource(override val size: Long, val prefix: ByteArray, val fill: Byte, val suffix: ByteArray = ByteArray(0)) : ByteSource {
        override fun read(offset: Long, length: Int): ByteArray {
            if (offset < 0 || offset >= size || length <= 0) return ByteArray(0)
            val n = minOf(length.toLong(), size - offset).toInt()
            val out = ByteArray(n)
            for (i in 0 until n) {
                val p = offset + i
                out[i] = if (p < prefix.size) prefix[p.toInt()] else if (p >= size - suffix.size) suffix[(p - (size - suffix.size)).toInt()] else fill
            }
            return out
        }
    }

    private fun check(label: String, insp: FormatInspector, src: ByteSource) {
        val c = CountingSource(src)
        val t0 = System.nanoTime()
        try { insp.inspect(c, "f") } catch (t: Throwable) { fail("$label: exception escaped: $t") }
        val ms = (System.nanoTime() - t0) / 1_000_000
        if (ms > 2000) fail("$label: took $ms ms")
        if (c.bytes > FormatInspector.MAX_READ_BYTES) fail("$label: read ${c.bytes} bytes > MAX_READ_BYTES")
        if (c.calls > 20000) fail("$label: ${c.calls} read calls")
    }
    private fun checkBytes(label: String, insp: FormatInspector, b: ByteArray) = check(label, insp, ByteArraySource(b))

    private fun gz(raw: ByteArray) = ByteArrayOutputStream().also { o -> GZIPOutputStream(o).use { it.write(raw) } }.toByteArray()
    private fun zip1(name: String, raw: ByteArray): ByteArray {
        val zb = ByteArrayOutputStream()
        ZipOutputStream(zb).use { z -> z.putNextEntry(ZipEntry(name)); z.write(raw); z.closeEntry() }
        return zb.toByteArray()
    }

