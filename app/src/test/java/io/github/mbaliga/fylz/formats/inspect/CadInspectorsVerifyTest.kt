    @Test(timeout = 600000) fun fuzzPrefixes() {
        for ((name, insp, b) in fixtures()) for (p in positions(b.size + 1, 1500)) checkBytes("$name prefix $p", insp, b.copyOf(p))
    }

    @Test(timeout = 600000) fun fuzzByteFlips() {
        for ((name, insp, b) in fixtures()) for (p in positions(b.size, 1500)) for (v in intArrayOf(0x00, 0xFF, 0x7F, 0x80)) {
            val c = b.copyOf(); c[p] = v.toByte(); checkBytes("$name flip@$p=$v", insp, c)
        }
    }

    @Test(timeout = 600000) fun fuzzFieldOverwrites() {
        for ((name, insp, b) in fixtures()) for (p in positions(b.size - 3, 1500)) for (v in longArrayOf(0xFFFFFFFFL, 0x7FFFFFFFL, 0L)) {
            val c = b.copyOf(); for (k in 0 until 4) c[p + k] = ((v shr (8 * k)) and 0xFF).toByte()
            checkBytes("$name u32le@$p=$v", insp, c)
            val d = b.copyOf(); for (k in 0 until 4) d[p + k] = ((v shr (8 * (3 - k))) and 0xFF).toByte()
            checkBytes("$name u32be@$p=$v", insp, d)
        }
        // 64-bit overwrites (FBX 7.5 wide records, ZIP64-ish)
        for ((name, insp, b) in fixtures()) for (p in positions(b.size - 7, 600)) {
            val c = b.copyOf(); for (k in 0 until 8) c[p + k] = 0xFF.toByte(); checkBytes("$name u64ff@$p", insp, c)
            val d = b.copyOf(); for (k in 0 until 8) d[p + k] = if (k == 7) 0x7F else 0xFF.toByte(); checkBytes("$name u64max@$p", insp, d)
        }
    }

    @Test(timeout = 600000) fun fuzzUniformAndRandom() {
        val rnd = Random(12345)
        val all = fixtures()
        val insps = all.map { it.second }.distinct()
        val magics = all.map { it.first to it.third.copyOf(minOf(it.third.size, 32)) }
        for (insp in insps) {
            for (n in intArrayOf(0, 1, 3, 4, 11, 12, 27, 80, 84, 85, 100, 1000, 4096, 70000)) {
                checkBytes("${insp.formatIds} zeros $n", insp, ByteArray(n))
                checkBytes("${insp.formatIds} ff $n", insp, ByteArray(n) { 0xFF.toByte() })
            }
        }
        for ((name, insp, b) in all) {
            val magic = b.copyOf(minOf(b.size, 40))
            for (iter in 0 until 60) {
                val rest = ByteArray(rnd.nextInt(3000)); rnd.nextBytes(rest)
                checkBytes("$name magic+random #$iter", insp, cat(magic, rest))
            }
            // random tail replacement while keeping first half
            for (iter in 0 until 60) {
                val keep = rnd.nextInt(b.size + 1)
                val rest = ByteArray(rnd.nextInt(500)); rnd.nextBytes(rest)
                checkBytes("$name half+random #$iter", insp, cat(b.copyOf(keep), rest))
            }
        }
    }

    @Test(timeout = 600000) fun hugeVirtualFiles() {
        val sizes = longArrayOf(1L shl 24, 50L * 1024 * 1024 * 1024)
        for ((name, insp, b) in fixtures()) for (sz in sizes) for (fill in byteArrayOf(0, 0xFF.toByte(), 0x20, 0x30, 0x0A)) {
            check("$name huge $sz fill $fill", insp, VirtualSource(maxOf(sz, b.size.toLong()), b, fill))
            check("$name huge+suffix $sz fill $fill", insp, VirtualSource(maxOf(sz, b.size.toLong()), b, fill, b))
        }
        // binary STL whose declared count exactly matches a huge size
        val n = 20_000_000L
        val hdr = cat(ByteArray(80), le(n))
        check("stl exact huge", CadStlInspector, VirtualSource(84 + 50 * n, hdr, 0))
        check("stl exact huge nonzero", CadStlInspector, VirtualSource(84 + 50 * n, hdr, 0x3F))
        val hdr2 = cat(ByteArray(80), le(n))
        check("stl 200k exact", CadStlInspector, VirtualSource(84 + 50 * 200000L, cat(ByteArray(80), le(200000)), 0x3F))
    }

    @Test(timeout = 600000) fun bigStoredZipStep() {
        val pad = ByteArray(9 * 1024 * 1024) { ' '.code.toByte() }
        val body = ("ISO-10303-21;\nHEADER;\nFILE_SCHEMA(('AUTOMOTIVE_DESIGN'));\nENDSEC;\nDATA;\n/*").toByteArray() + pad + "*/\n#1=PRODUCT('a','b','',(#2));\nENDSEC;\nEND-ISO-10303-21;\n".toByteArray()
        val crc = java.util.zip.CRC32().also { it.update(body) }
        val zb = ByteArrayOutputStream()
        ZipOutputStream(zb).use { z ->
            val e = ZipEntry("big.stp"); e.method = ZipEntry.STORED; e.size = body.size.toLong(); e.compressedSize = body.size.toLong(); e.crc = crc.value
            z.putNextEntry(e); z.write(body); z.closeEntry()
        }
        checkBytes("step stored zip 9MB", CadStepInspector, zb.toByteArray())
    }

