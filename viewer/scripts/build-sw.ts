/**
 * Generates dist/sw.js: precaches every file in dist/ (JS, CSS, WASM, fonts, workers) so the app
 * works fully offline after the first load. Also implements the share-target POST handler.
 */
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

const dist = join(import.meta.dirname, "..", "dist");
const files: string[] = [];
(function walk(d: string) {
  for (const n of readdirSync(d)) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (n !== "sw.js") files.push(relative(dist, p).split("\\").join("/"));
  }
})(dist);
files.sort();
const h = createHash("sha256");
for (const f of files) { h.update(f); h.update(readFileSync(join(dist, f))); }
const version = h.digest("hex").slice(0, 12);
const urls = ["./", ...files];

writeFileSync(join(dist, "sw.js"), `/* generated by scripts/build-sw.ts — do not edit */
const VERSION = ${JSON.stringify(version)};
const CACHE = "fv-precache-" + VERSION;
const SHARE = "fv-share";
const URLS = ${JSON.stringify(urls)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("fv-precache-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("message", (e) => { if (e.data === "version") e.source && e.source.postMessage({ sw: VERSION }); });
self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // never touch cross-origin requests (we make none)
  if (req.method === "POST" && url.pathname.endsWith("/share-target")) {
    e.respondWith((async () => {
      const form = await req.formData();
      const cache = await caches.open(SHARE);
      for (const k of await cache.keys()) await cache.delete(k);
      let n = 0;
      for (const v of form.getAll("file")) {
        if (typeof v === "string") continue;
        await cache.put("./shared/" + n + "?name=" + encodeURIComponent(v.name), new Response(v, { headers: { "content-type": v.type || "application/octet-stream" } }));
        n++;
      }
      return Response.redirect("./?share=" + n, 303);
    })());
    return;
  }
  if (req.method !== "GET") return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: req.mode === "navigate", ignoreVary: true });
    if (hit) return hit;
    if (req.mode === "navigate") { const idx = await cache.match("./"); if (idx) return idx; }
    return fetch(req);
  })());
});
`);
console.log("sw.js written: " + urls.length + " precached files, version " + version);
